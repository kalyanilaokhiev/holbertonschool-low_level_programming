#include <stdio.h>

/**
 * op_add - adding
 *
 * @a: num 1
 * @b: num 2
 *
 * Return: sum
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - subtracting
 *
 * @a: num 1
 * @b: num 2
 *
 * Return: subtract
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - multiplying
 *
 * @a: num 1
 * @b: num 2
 *
 * Return: multiplication
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - dividing
 *
 * @a: num 1
 * @b: num 2
 *
 * Return: division
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - modulus
 *
 * @a: num 1
 * @b: num 2
 *
 * Return: remainder
 */
int op_mod(int a, int b)
{
	return (a % b);
}
